"""Independent direct-geodesic and high-precision horizon fixtures.

Original computed numbers, not downloaded reference assets. The row first
offsets 100 international feet left, then follows the original horizontal heading
from that offset. Station zero is at that offset; later stations are multiples
of 0.5 international mile.
"""
import argparse
from pathlib import Path
import pyproj
import mpmath as mp

ROOT = Path(__file__).resolve().parents[1]
TARGET = ROOT / "crates/earth-math/tests/fixtures/survey_reference.rs"


def generate():
    if (pyproj.__version__, pyproj.proj_version_str, mp.__version__) != ("3.7.2", "9.5.1", "1.3.0"):
        raise RuntimeError("Requires pyproj3.7.2/PROJ9.5.1/mpmath1.3.0")
    geod = pyproj.Geod(a=6378137, rf=298.257223563)
    rows = []
    for latitude, longitude, heading in [(29.305549, -94.767015, 0.0), (29.305549, -94.767015, 90.0), (89.9, 179.9, 15.0), (-45.0, -179.99, 270.0)]:
        start_lon, start_lat, _ = geod.fwd(longitude, latitude, heading-90.0, 30.48)
        for station in [0, 1, 20, 80]:
            distance = station*804.672
            lon, lat, back_azimuth = geod.fwd(start_lon, start_lat, heading, distance)
            forward = (back_azimuth+180.0) % 360.0
            rows.append(f"    ([{latitude!r}, {longitude!r}, {heading!r}], {station}, [{lat!r}, {lon!r}, {forward!r}]),")
    mp.mp.dps = 70
    radius = mp.mpf(6378137)
    eye = mp.mpf("1.72")
    eye_angle = mp.acos(radius/(radius+eye))
    horizon = []
    for miles in [1, 4, 8, 12, 16, 40]:
        angle = mp.mpf(miles)*mp.mpf("1609.344")/radius
        hidden = mp.mpf(0) if angle <= eye_angle else radius/mp.cos(angle-eye_angle)-radius
        hidden = min(hidden,mp.mpf("30.48"))
        horizon.append(f"    ({float(miles*1609.344)!r}, {float(hidden)!r}),")
    return ("// Original fixtures generated by scripts/verify_survey.py.\n"
            "// PROJ9.5.1 direct geodesics; mpmath70-digit equatorial tangency.\n"
            "pub type RowFixture = ([f64; 3], usize, [f64; 3]);\n"
            "#[rustfmt::skip]\npub const ROWS: &[RowFixture] = &[\n"+"\n".join(rows)+"\n];\n"
            "#[rustfmt::skip]\npub const HIDDEN: &[(f64, f64)] = &[\n"+"\n".join(horizon)+"\n];\n")


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    output = generate()
    if args.check:
        if TARGET.read_text(encoding="utf-8") != output:
            raise SystemExit("Survey reference fixtures differ")
    else:
        TARGET.write_text(output,encoding="utf-8",newline="\n")
    print("Verified 16 direct row stations and 6 independent equatorial hidden-height fixtures.")
