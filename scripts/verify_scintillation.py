"""Independent HV5/7 integral fixtures using mpmath quadrature, not gamma expansion.

Original computed numbers; equations: Pirandola, Phys. Rev. Research 3, 023130
(2021), Appendix C, https://doi.org/10.1103/PhysRevResearch.3.023130 .
Run with optional cached Python dependencies (mpmath1.3.0). No source assets.
"""
import argparse
from pathlib import Path
import mpmath as mp

ROOT = Path(__file__).resolve().parents[1]
TARGET = ROOT / "crates/earth-math/tests/fixtures/scintillation_integral.rs"


def generate():
    if mp.__version__ != "1.3.0":
        raise RuntimeError("Reference generation requires mpmath1.3.0")
    mp.mp.dps = 55
    def cn2(h):
        return (mp.mpf("5.94e-53") * (mp.mpf(21) / 27) ** 2 * h**10
                * mp.exp(-h / 1000) + mp.mpf("2.7e-16") * mp.exp(-h / 1500)
                + mp.mpf("1.7e-14") * mp.exp(-h / 100))
    rows = []
    for height in ["0", "1.72", "100", "1000", "5000", "10000", "20000", "40000", "120000"]:
        h = mp.mpf(height)
        integral = mp.quad(lambda x: cn2(h + x) * x ** (mp.mpf(5) / 6),
                           [0, 100, 1000, 10000, 50000, 200000, mp.inf])
        variance = mp.mpf("2.25") * (2 * mp.pi / mp.mpf("550e-9")) ** (mp.mpf(7) / 6) * integral
        rows.append(f"    ({float(h)!r}, {float(variance)!r}),")
    return ("// Generated by scripts/verify_scintillation.py; original computed values.\n"
            "// mpmath1.3.0, 55 decimal digits, direct split-domain quadrature.\n"
            "#[rustfmt::skip]\npub const ZENITH: &[(f64, f64)] = &[\n" + "\n".join(rows) + "\n];\n")


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    value = generate()
    if args.check:
        if TARGET.read_text(encoding="utf-8") != value:
            raise SystemExit("Scintillation quadrature fixtures differ")
    else:
        TARGET.write_text(value, encoding="utf-8", newline="\n")
    print("Verified9 direct high-precision reference-column integrals.")
