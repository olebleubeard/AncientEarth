"""Independent original source-post fixtures for the runtime Copernicus importer.

Reads already-reviewed cached official source TIFFs using Rasterio/GDAL, never
the Rust TIFF decoder. Pixel coordinates come from GDAL's geotransform, including
its PixelIsPoint half-pixel convention. No download or asset modification.
"""
import argparse
import hashlib
from pathlib import Path
import rasterio

ROOT = Path(__file__).resolve().parents[1]
TARGET = ROOT / "crates/earth-math/tests/fixtures/copernicus_source.rs"
SOURCES = [
    ("N29W095", 29, -95, "69f6dec846388ab5b64f14c1f2689b59bc567fb4697fa0ce1a03c379e718b47c"),
    ("N35E138", 35, 138, "06d8b0fa3ebe34ec2c2d2900d7576aeb457beb40f0216d9bebd234610e5ecf03"),
]
INDICES = [(0, 0), (8, 8), (80, 160), (800, 1600), (1600, 800), (2400, 2400), (3592, 3592)]


def generate(cache):
    output = ["// Original source-post values generated by scripts/verify_copernicus_import.py.",
              "// Official AWS Copernicus GLO-30 2021; source rights/provenance retained by project.",
              "// GDAL/Rasterio coordinates, independently decoded Float32 metre heights.",
              "pub type SourcePost = (&'static str, i32, i32, usize, usize, f64, f64, f64);",
              "#[rustfmt::skip]", "pub const POSTS: &[SourcePost] = &["]
    for name, south, west, digest in SOURCES:
        path = cache / f"{name}.tif"
        if hashlib.sha256(path.read_bytes()).hexdigest() != digest:
            raise ValueError(f"Unrecognized source bytes: {name}")
        with rasterio.open(path) as source:
            if source.shape != (3600, 3600) or source.crs.to_epsg() != 4326 or source.tags().get("AREA_OR_POINT") != "Point":
                raise ValueError(f"Unexpected source registration: {name}")
            values = source.read(1)
            for row, column in INDICES:
                longitude, latitude = map(float, source.xy(row, column))
                if abs(longitude - (west + column/3600)) > 1e-12 or abs(latitude - (south+1-row/3600)) > 1e-12:
                    raise ValueError("Source center disagrees with declared point lattice")
                output.append(f'    ("{name}", {south}, {west}, {row}, {column}, {latitude!r}, {longitude!r}, {float(values[row,column])!r}),')
    return "\n".join(output + ["];", ""])


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--cache", type=Path, default=ROOT / ".cache/terrain")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    content = generate(args.cache)
    if args.check:
        if TARGET.read_text(encoding="utf-8") != content:
            raise SystemExit("Source-post fixtures differ")
    else:
        TARGET.write_text(content, encoding="utf-8", newline="\n")
    print("Verified14 source posts, point registration and both official source SHA256 identities.")
