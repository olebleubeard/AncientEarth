"""Generate independent WGS84 direct-geodesic coverage extrema with PROJ.

Requires optional scripts/requirements-terrain.txt (pyproj3.7.2/PROJ9.5.1).
No downloaded reference data: all numbers are independently computed here.
PROJ uses Karney geodesics; the production query enclosure instead follows a
metric lower bound. See https://proj.org/en/stable/geodesic.html.
The finite azimuth sweep supplements, not replaces, the enclosure proof.
"""
from pathlib import Path
import argparse
import math
import pyproj

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "crates/earth-math/tests/fixtures/topography_proj.rs"
CASES = [
    (0.0, 0.0, 160934.4),
    (45.0, -95.0, 160934.4),
    (80.0, 179.8, 100000.0),
    (20.0, 179.999, 160934.4),
    (-45.0, -179.99, 160934.4),
    (89.0, 179.7, 160934.4),
    (-89.0, -179.7, 160934.4),
    (90.0, 31.0, 1.0),
    (-90.0, -77.0, 1.0),
    (0.0, 180.0, 0.000001),
    (12.3, 44.5, 0.000000001),
    (0.0, 0.0, 15000000.0),
    (75.0, 0.0, 15000000.0),
    (0.0, 0.0, 1000000000.0),
]


def generate():
    geodesic = pyproj.Geod(a=6378137.0, rf=298.257223563)
    rows = []
    for latitude, longitude, radius in CASES:
        points = [(latitude, longitude)]
        for fraction in (0.25, 0.5, 1.0):
            for azimuth in range(720):
                lon, lat, _ = geodesic.fwd(longitude, latitude, azimuth * 0.5, fraction * radius)
                lon = longitude + ((lon - longitude + 180.0) % 360.0 - 180.0)
                assert math.isfinite(lon) and math.isfinite(lat)
                points.append((lat, lon))
        latitudes, longitudes = zip(*points)
        rows.append(f"    DirectBounds {{ center: [{latitude!r}, {longitude!r}], radius_m: {radius!r}, latitude: [{min(latitudes)!r}, {max(latitudes)!r}], longitude_unwrapped: [{min(longitudes)!r}, {max(longitudes)!r}], samples: {len(points)} }},")
    return """// Generated by scripts/verify_topography_bounds.py, not downloaded data.
// pyproj 3.7.2 / PROJ 9.5.1; WGS84 a=6378137, rf=298.257223563.
// Each case includes centre plus 720 azimuths at three radial fractions.
pub struct DirectBounds {
    pub center: [f64; 2],
    pub radius_m: f64,
    pub latitude: [f64; 2],
    pub longitude_unwrapped: [f64; 2],
    pub samples: usize,
}
#[rustfmt::skip]
pub const CASES: &[DirectBounds] = &[
""" + "\n".join(rows) + "\n];\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    if pyproj.__version__ != "3.7.2" or pyproj.proj_version_str != "9.5.1":
        raise SystemExit("Use the pinned pyproj3.7.2 / PROJ9.5.1 reference environment.")
    result = generate()
    if args.check:
        if OUTPUT.read_text(encoding="utf-8") != result:
            raise SystemExit("Topography direct-geodesic reference differs.")
    else:
        OUTPUT.write_text(result, encoding="utf-8", newline="\n")
    print(f"Verified {len(CASES)} cases / {len(CASES) * 2161} direct samples with PROJ9.5.1.")


if __name__ == "__main__":
    main()
