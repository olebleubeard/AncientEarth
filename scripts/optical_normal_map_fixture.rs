use earth_math::{EnuBasis,Vec3d,ecef_to_geodetic};
use serde_json::{Value,json};
pub use trace::Fixture;
fn split(h:f64)->[f32;2]{let high=h as f32;[high,(h-f64::from(high)) as f32]}
pub fn build()->Fixture{
    let mut fixture=trace::build_metric_fast();
    let source=&fixture.cases["cases"][0]["canonical_inputs"];
    let origin=&source["origin_ecef_m"];
    let eye=ecef_to_geodetic(Vec3d::new(origin[0].as_f64().unwrap(),origin[1].as_f64().unwrap(),origin[2].as_f64().unwrap())).unwrap();
    let basis=EnuBasis::at(eye);let axis=[basis.east.z,basis.up.z,-basis.north.z];
    let (axis_lower,axis_upper)=packet::axis_intervals(eye).unwrap();
    let e=packet::eccentricity_interval().unwrap();
    let encoded_eye=[f32::from_le_bytes(fixture.uniform[8..12].try_into().unwrap()),f32::from_le_bytes(fixture.uniform[12..16].try_into().unwrap())];
    let eye_residual=packet::residual_for_split(eye.height_m,encoded_eye).unwrap();
    let mut inputs=Vec::<[f32;4]>::new();let mut cases=Vec::<Value>::new();
    for (anchor,a,b) in [(eye.height_m,0.,0.),(-30.,1e-6,-2e-6),(2000.,-0.01,0.02),(50000.,0.1,-0.15),(120000.,-0.2,0.3),(0.,0.5,-0.5)]{
        let encoded_anchor=split(anchor);let anchor_residual=packet::residual_for_split(anchor,encoded_anchor).unwrap();
        for theta in [0_f32,0.125,0.5,1.]{
            let start=[0_f32,a as f32,b as f32,0.];
            let coeffs=[[10_f32,2e-7,-3e-7,0.],[-0.125,1e-8,2e-8,0.],[0.0625,-1e-8,1e-8,0.],[-0.03125,2e-9,-1e-9,0.]];
            inputs.extend([
                [encoded_anchor[0],encoded_anchor[1],0.,0.],
                [axis_lower[0],axis_lower[1],axis_lower[2],0.],
                [axis_upper[0],axis_upper[1],axis_upper[2],0.],
                [e[0],e[1],eye_residual[0],eye_residual[1]],
                [anchor_residual[0],anchor_residual[1],theta,0.],start,
            ]);
            inputs.extend(coeffs);
            cases.push(json!({"anchor_canonical_m":anchor,"anchor_canonical_bits":anchor.to_bits(),"encoded_anchor":encoded_anchor,"anchor_residual":anchor_residual,
                "start_q":start,"coefficients":coeffs,"theta":theta}));
        }
    }
    let bindings=fixture.shader.find("\n@group(0) @binding(1)").unwrap();
    fixture.shader.truncate(bindings);
    for path in ["scripts/optical_normal_local.wgsl","scripts/optical_normal_scene_curve.wgsl","scripts/optical_normal_map_interval.wgsl"]{
        fixture.shader.push_str(&std::fs::read_to_string(path).unwrap());
    }
    fixture.shader.push_str(ENTRY);
    fixture.rays=inputs.iter().flatten().flat_map(|x|x.to_le_bytes()).collect();
    fixture.count=cases.len() as u32;fixture.record_words=24;fixture.output_bytes=u64::from(fixture.count)*96;
    fixture.cases=json!({"scope":"Canonical point/velocity interval correctness only, no ray integration/contact/timing/adoption claim.",
        "reference_checkpoint":"artifacts/optical-height-trace-fast-metric-uniform.bin",
        "uniform_provenance":"Regenerated by the unchanged build_metric_fast fixture; no byte-identity claim is inferred from the reference path.",
        "canonical_eye_origin_ecef_m":origin,"canonical_eye_geodetic":[eye.lat_deg,eye.lon_deg,eye.height_m],
        "eye_height_m":eye.height_m,"encoded_eye_height":encoded_eye,
        "canonical_f64_bits":{"eye_height_m":eye.height_m.to_bits(),"axis_before_normalization":axis.map(f64::to_bits),
            "eccentricity":earth_math::WGS84_E2.to_bits(),"eye_geodetic":[eye.lat_deg.to_bits(),eye.lon_deg.to_bits(),eye.height_m.to_bits()]},
        "canonical_axis_before_exact_normalization":axis,"axis_lower":axis_lower,"axis_upper":axis_upper,
        "eccentricity_canonical":earth_math::WGS84_E2,"eccentricity_interval":e,"eye_residual":eye_residual,
        "input_vectors_per_case":10,"output_words_per_case":24,
        "record_layout":"position lower xyz/valid;position upper xyz/0;velocity lower xyz/0;velocity upper xyz/0;ordinary float position xyz/0;computed-point radius lower upper/0/0",
        "cases":cases});
    fixture
}
